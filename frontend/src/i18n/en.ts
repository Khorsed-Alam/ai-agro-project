type TranslationLeaf = string | number | boolean | null | undefined;

export type DeepTranslationKeys<T> = {
  [Key in keyof T & (string | number)]: T[Key] extends TranslationLeaf
    ? `${Key}`
    : T[Key] extends readonly unknown[]
      ? never
      : `${Key}` | `${Key}.${DeepTranslationKeys<T[Key]>}`
}[keyof T & (string | number)];

export type TranslationKey = DeepTranslationKeys<TranslationTree>;
export type TranslationTreeType = TranslationTree;

type WidenTranslationTree<T> = {
  [Key in keyof T]: T[Key] extends string ? string : WidenTranslationTree<T[Key]>;
};

export type TranslationResource = WidenTranslationTree<TranslationTree>;
export type TranslationValue = TranslationLeaf;
export type TranslationValues = Record<string, TranslationValue>;
